def w(path, fields, rows):
    os.makedirs("data", exist_ok=True)
    with open(path, "w", newline="") as fh:
        cw = csv.writer(fh)
        cw.writerow(fields)
        cw.writerows(rows)
    print(f"{path}: {len(rows)} rows")


