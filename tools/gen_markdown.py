#!/usr/bin/env python3
"""Render the data registers as Markdown so they are readable on GitHub without the site.

Single source of truth stays in assets/data/*.js; these .md files are generated.

    python3 tools/gen_markdown.py            # write the .md views
    python3 tools/gen_markdown.py --check     # fail if they are out of date

Writes: requirements.md, questions.md, suggestions.md, flagged-for-review.md,
        sources.md, coordination/review.json, coordination/tasks.json
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
from check_site import load_datasets, js_to_json  # noqa: E402

GEN = ("<!-- GENERATED by tools/gen_markdown.py from assets/data/*.js — do not edit here; "
       "edit the dataset and re-run the generator. -->\n")

PAGES = {
    "requirements": ("requirements.md", "Requirements register",
                      "What “done” means. Status is only `met` where a file in this repo satisfies the row today."),
    "questions": ("questions.md", "Open questions gating a decision",
                  "Each row: what we have, what we lack, how to find out, and the provisional answer in use."),
    "suggestions": ("suggestions.md", "Suggestions register (for review)",
                    "Priority = (Impact + Confidence) x 2 - Effort - Risk, computed by the site. "
                    "Dispositions are left open on purpose: nothing that changes behaviour was adopted without "
                    "being marked as needing a choice."),
    "flags": ("flagged-for-review.md", "Flagged for review",
              "Irregularities and unverified items found while collecting, verifying or building. None of these "
              "block the site or the merge; each is a request for judgement."),
    "sources": ("sources.md", "Source catalogue",
                "`verified=direct` means the page was opened and read; `snippet` means only a search extract was "
                "seen; `planned` means required but not yet obtained; `failed` is a recorded dead end."),
}


def slugify(t: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", t.lower()).strip("-")


def md_escape(v: object) -> str:
    s = "" if v is None else str(v)
    return s.replace("|", "\\|").replace("\n", "<br>")


def render(key: str, obj: dict) -> str:
    fname, title, blurb = PAGES[key]
    cols = obj["columns"]
    lines = [GEN, f"# {title}", "", f"_Source of truth: `assets/data` (dataset `{key}`). {blurb}_", ""]
    if isinstance(obj.get("rows"), list):
        head = [c.get("label") or c.get("t") or c["k"] for c in cols]
        lines.append("| " + " | ".join(head) + " |")
        lines.append("|" + "|".join([" --- "] * len(head)) + "|")
        keys = [c["k"] for c in cols]
        for row in obj["rows"]:
            rec = row if isinstance(row, dict) else dict(zip(keys, row))
            lines.append("| " + " | ".join(md_escape(rec.get(k)) for k in keys) + " |")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="verify the generated files are current")
    args = ap.parse_args()

    ds = load_datasets()
    targets: dict[Path, str] = {}
    for key in PAGES:
        if key not in ds:
            print(f"missing dataset {key}", file=sys.stderr)
            return 1
        name, _, _ = PAGES[key]
        targets[ROOT / name] = render(key, js_to_json(ds[key][1]))

    # machine-readable coordination copies
    (ROOT / "coordination").mkdir(exist_ok=True)
    flags = js_to_json(ds["flags"][1])
    fkeys = [c["k"] for c in flags["columns"]]
    targets[ROOT / "coordination" / "review.json"] = json.dumps(
        {"generated_from": "assets/data/review.js",
         "note": "Machine-readable copy of the review register. Nothing here blocks a merge; "
                 "needs review = published and non-blocking.",
         "items": [dict(zip(fkeys, r)) for r in flags["rows"]]}, indent=2, ensure_ascii=False) + "\n"

    coord = (ROOT / "COORDINATION.md").read_text(encoding="utf-8")
    board = []
    for m in re.finditer(
            r"^\|\s*(T\d+)\s*\|\s*([^|]+?)\s*\|\s*([^|]*?)\s*\|\s*([^|]*?)\s*\|\s*([^|]*?)\s*\|\s*([^|]*?)\s*\|$",
            coord, flags=re.M):
        tid, title, status, owner, scope, src = (g.strip() for g in m.groups())
        board.append({"id": tid, "title": title, "status": status, "owner": owner.strip("`"),
                      "file_scope": [s.strip().strip("`") for s in scope.split(",") if s.strip() and s.strip() != "—"],
                      "sources_recorded": src})
    if not board:
        print("no tasks parsed from COORDINATION.md", file=sys.stderr)
        return 1
    targets[ROOT / "coordination" / "tasks.json"] = json.dumps(
        {"generated_from": "COORDINATION.md task board", "tasks": board}, indent=2, ensure_ascii=False) + "\n"

    stale = []
    for path, text in targets.items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(path.relative_to(ROOT).as_posix())
        else:
            path.write_text(text, encoding="utf-8")
            print("wrote", path.relative_to(ROOT))
    if args.check:
        if stale:
            print("out of date: " + ", ".join(stale), file=sys.stderr)
            return 1
        print("generated files are current")
    return 0


if __name__ == "__main__":
    sys.exit(main())
