#!/usr/bin/env python3
"""Build the 2026-11-19 review pages from the CSVs in data/.

Inputs (all committed in this session):
  data/roster_events_2026.csv
  data/colts_wr_chart_vs_gamebook_2026_w10.csv
  data/review_flags_2026-11-19.csv
  data/review_sources_2026-11-19.csv
  data/brief_status_reconciliation_2026-11-19.csv

Outputs:
  review/roster-events-2026-11-19.html
  review/flagged-for-review-2026-11-19.html

No network access. Values are copied from the CSVs; nothing is inferred.
"""
import csv
import html
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data"
OUT = ROOT / "review"


def load(name):
    with open(DATA / name, newline="", encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def esc(v):
    return html.escape(v or "", quote=True)


def links(text):
    """Turn each URL in a cell into a clickable link, keeping the rest as text."""
    out = []
    for part in (text or "").split(" ; "):
        part = part.strip()
        if not part:
            continue
        url = part.split(" ")[0]
        rest = part[len(url):]
        if url.startswith("https://"):
            out.append(f'<a href="{esc(url)}">{esc(url)}</a>{esc(rest)}')
        else:
            out.append(esc(part))
    return "<br>".join(out)


def table(headers, rows, link_cols=()):
    head = "".join(f"<th>{esc(h)}</th>" for h in headers)
    body = []
    for r in rows:
        cells = []
        for h in headers:
            key = h
            val = r.get(key, "")
            if key in link_cols:
                cells.append(f"<td>{links(val)}</td>")
            else:
                cells.append(f"<td>{esc(val)}</td>")
        body.append("<tr>" + "".join(cells) + "</tr>")
    return (
        '<div class="table-wrap"><table><thead><tr>' + head + "</tr></thead><tbody>"
        + "".join(body) + "</tbody></table></div>"
    )


def page(title, lede, sections, banner=""):
    return f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{esc(title)}</title>
<link rel="stylesheet" href="../assets/style.css">
<style>
  .table-wrap {{ overflow-x: auto; margin: 1rem 0; }}
  table {{ border-collapse: collapse; width: 100%; font-size: 0.85rem; }}
  th, td {{ border: 1px solid #ccc; padding: 4px 6px; vertical-align: top; text-align: left; }}
  th {{ background: #f2f2f2; }}
  .banner {{ background: #fff4d6; border: 1px solid #d9a400; padding: 0.6rem 0.8rem; }}
</style>
</head>
<body>
<main class="wrap">
<p><a href="../index.html">&larr; Hub</a></p>
<h1>{esc(title)}</h1>
{('<p class="banner">' + esc(banner) + '</p>') if banner else ''}
<p>{esc(lede)}</p>
{''.join(sections)}
<p class="muted">Generated by tools/build_review_2026_11_19.py from the CSVs in data/. Values are copied, not inferred.</p>
</main>
</body>
</html>
"""


def build_roster():
    events = load("roster_events_2026.csv")
    chart = load("colts_wr_chart_vs_gamebook_2026_w10.csv")
    recon = load("brief_status_reconciliation_2026-11-19.csv")
    s1 = (
        "<h2>1. Roster and transaction events (BAL, IND, MIA, SEA)</h2>"
        "<p>Each row shows the event, its verification status, the official URLs it was read from, "
        "and the league reserve-log check. Blank means the source could not confirm the value.</p>"
        + table(
            ["event_id", "event_date", "club", "player", "event_type", "detail",
             "verification_status", "official_urls", "league_reserve_log_check", "note"],
            events, link_cols=("official_urls",))
    )
    s2 = (
        "<h2>2. Colts receivers: club chart against the Game Book</h2>"
        "<p>The club chart is captioned unofficial. The Game Book is the official game-day record.</p>"
        + table(
            ["player", "colts_chart_listing_2026_11_10", "gamebook_2026_11_15_status",
             "gamebook_jersey", "gamebook_url", "note"],
            chart, link_cols=("gamebook_url",))
    )
    s3 = (
        "<h2>3. Requirement status: register as written against this review</h2>"
        "<p>Proposed statuses are for the integration owner to apply. The register itself is not edited here.</p>"
        + table(
            ["req_id", "register_status_as_written", "status_proposed_by_this_review",
             "evidence_on_main", "evidence_path", "note"],
            recon, link_cols=())
    )
    return page(
        "Roster events and requirement status (2026-11-19)",
        "Official-source roster events for four clubs, the Colts receiver check, and the register rows "
        "this review changed or confirmed. Every row carries its source. Anything not read is blank.",
        [s1, s2, s3],
    )


def build_flags():
    flags = load("review_flags_2026-11-19.csv")
    sources = load("review_sources_2026-11-19.csv")
    s1 = (
        "<h2>Flagged items (do not block merge)</h2>"
        + table(
            ["flag_id", "severity", "category", "finding", "evidence",
             "owner_decision_needed", "related_requirements", "resolution_path"],
            flags, link_cols=())
    )
    s2 = (
        "<h2>Source register for this review</h2>"
        "<p>Every URL cited by this review, with what was read and when. "
        "Where a source could not be read, the row says so.</p>"
        + table(
            ["url", "source_type", "read_on_utc", "read_result", "used_for"],
            sources, link_cols=("url",))
    )
    return page(
        "Flagged for Review (2026-11-19)",
        "Irregularities and unverified items from the 2026-11-19 review of the repository. "
        "Each flag lists its evidence. None of these flags blocks merge.",
        [s1, s2],
        banner="Flagged for Review. Items here need an owner decision or a re-check. They do not block any merge.",
    )


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "roster-events-2026-11-19.html").write_text(build_roster(), encoding="utf-8")
    (OUT / "flagged-for-review-2026-11-19.html").write_text(build_flags(), encoding="utf-8")
    print("wrote review/roster-events-2026-11-19.html and review/flagged-for-review-2026-11-19.html")


if __name__ == "__main__":
    main()
