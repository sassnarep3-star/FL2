#!/usr/bin/env python3
"""
tools/build_landing_readiness.py — integrated decision-readiness table (T26/T27).

Merges the two independent registers produced in parallel sessions:
  * fl2-lines/data/registers/readiness.csv   (R01-R74, session 39dd0836/74f76e34)
  * data/decision_readiness.json             (DR-01-DR-72, session-65556dd2)
into one landing-page table: one row per requirement, with the gate that blocks
it and the number that would clear it, plus an integration-update column where
the other session's artifacts changed the picture.

Rows are keyed by requirement text order (R01..R67 map 1:1 to DR-01..DR-67;
R68..R74 follow; DR-68 has no R counterpart and is appended). Emits
data/landing_readiness.js (window.FL2_READINESS) for the landing page renderer.
Deterministic; stdlib only.
"""
from __future__ import annotations

import csv
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# Integration updates recorded by session-65556dd2 against fl2-lines register rows.
UPDATES = {
    "R01": "Session-65556dd2 price store adds 1,088 paired open/close rows (2021 WSGT) and 13 Week-11 opening captures with timestamps (data/price_snapshots.csv); Week-11 closing pending pre-kickoff.",
    "R18": "Opening coverage no longer 0%: 13 Week-11 games carry opening captures and fair|market|difference columns (data/origination_week11.csv), generated before the first kickoff (gate G4 pass).",
    "R21": "Two dated Week-10 reads now retained with clock times and digests (data/captures/: 2026-11-14 transcription, 2026-11-16 official recount).",
    "R23": "13/13 Week-11 venues transcribed from the official nfl.com schedule page; 3 venue-name discrepancies flagged (NRG/Reliant, FedExField/Northwest, Estadio Azteca/Banorte).",
    "R35": "A second, independently pre-registered shadow baseline (SB-1.0.0) recorded 13 forecasts at 2026-11-16T02:45Z, registration commit 55b94c1 — both forecast sets precede the first kickoff.",
    "R42": "Kyle McCord in-line-for-start verified via a dated nfl.com news row; Malik Willis IR captured in the reserve registry (data/availability_graph.json). Lock/Brissett items still need their article URLs.",
    "R46": "Tyler Huntley out-for-season confirmed via dated nfl.com news; Lamar Jackson 'expected to miss 6-10 weeks' per the Nov 13 nfl.com news roundup (official wording, not the IR claim).",
    "R64": "Reserve registry opened with the Malik Willis injured-reserve entry (dated nfl.com source) in data/availability_graph.json; rule 'not listed never means available' encoded.",
    "R68": "SB-1 rule text pinned at registration commit 55b94c1 and echoed in every forecast row (data/forecast_ledger.json).",
    "R16": "Exact-binomial luck bands at -110 added (n=50..2243): at n=100 pure luck spans -16.0%..+16.5% ROI (5th-95th percentile) — data/development_panel.json.",
}


def main() -> int:
    rows_r = list(csv.DictReader(open(os.path.join(ROOT, "fl2-lines", "data", "registers", "readiness.csv"))))
    reg_d = json.load(open(os.path.join(ROOT, "data", "decision_readiness.json")))
    rows_d = reg_d["rows"]

    out = []
    for i, r in enumerate(rows_r):
        d = rows_d[i] if i < 67 else None  # DR-01..DR-67 map 1:1
        out.append({
            "id": r["id"],
            "requirement": r["requirement"],
            "status": r["status"],
            "gate": r["gate_blocking"],
            "clearing_number": r["clearing_number"],
            "update": UPDATES.get(r["id"], ""),
            "evidence": r["evidence"],
            "official_source": r["official_source"],
            "second_register": (d["id"] + " (" + d["status"] + ")") if d else "",
        })
    # DR-68 has no R counterpart
    d68 = next((x for x in rows_d if x["id"] == "DR-68"), None)
    if d68:
        out.append({
            "id": d68["id"], "requirement": d68["requirement"], "status": d68["status"].upper(),
            "gate": d68["gate"], "clearing_number": d68["number_to_clear"],
            "update": "", "evidence": d68["evidence"], "official_source": d68["evidence_url"],
            "second_register": "only in session-65556dd2 register",
        })

    counts = {}
    for r in out:
        counts[r["status"]] = counts.get(r["status"], 0) + 1
    payload = {
        "meta": {
            "generated_by": "tools/build_landing_readiness.py",
            "generated_at_utc": "2026-11-16T03:40:00Z",
            "rows": len(out),
            "counts": counts,
            "registers": ["fl2-lines/data/registers/readiness.csv (R01-R74)",
                          "data/decision_readiness.json (DR-01-DR-72)"],
        },
        "rows": out,
    }
    js = ("// generated by tools/build_landing_readiness.py — do not hand-edit\n"
          "window.FL2_READINESS = " + json.dumps(payload, indent=1) + ";\n")
    with open(os.path.join(ROOT, "data", "landing_readiness.js"), "w") as fh:
        fh.write(js)
    print(f"landing readiness OK: {len(out)} rows, counts {counts}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
