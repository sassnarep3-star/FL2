#!/usr/bin/env python3
"""
tools/build_fl2_pages.py

Renders two generated blocks into the FL2 dashboard pages. Everything inside the
markers is overwritten on each run; everything outside is hand-written and kept.

  fl2-dashboard/index.html         <!-- BEGIN:readiness --> ... <!-- END:readiness -->
      from fl2-dashboard/data/decision-readiness.json
  fl2-dashboard/repo-review.html   <!-- BEGIN:audit --> ... <!-- END:audit -->
      from fl2-dashboard/data/repo-audit.json (written by tools/repo_audit.py)

Run order:  python3 tools/repo_audit.py && python3 tools/build_fl2_pages.py
"""
import collections
import html
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DASH = os.path.join(ROOT, "fl2-dashboard")

BADGE = {
    "Built": "verified",
    "Partial": "pending",
    "Framework": "design",
    "Blocked": "flagged",
    "Not started": "warn",
    "Decided": "design",
}
ORDER = ["Built", "Partial", "Framework", "Decided", "Blocked", "Not started"]


def esc(s):
    return html.escape(str(s if s is not None else ""), quote=True)


def replace_block(path, name, body):
    with open(path, encoding="utf-8") as fh:
        text = fh.read()
    pat = re.compile(r"(<!-- BEGIN:%s -->)(.*?)(<!-- END:%s -->)" % (name, name), re.S)
    if len(pat.findall(text)) != 1:
        raise SystemExit(f"{os.path.relpath(path, ROOT)}: expected exactly one {name} block")
    new = pat.sub(lambda m: m.group(1) + "\n" + body + "\n" + m.group(3), text)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(new)


def link(href, label):
    if href.startswith("http"):
        return f'<a href="{esc(href)}" target="_blank" rel="noopener">{esc(label)}</a>'
    return f'<a href="{esc(href)}">{esc(label)}</a>'


def readiness_block():
    with open(os.path.join(DASH, "data/decision-readiness.json"), encoding="utf-8") as fh:
        d = json.load(fh)
    rows = d["rows"]
    counts = collections.Counter(r["status"] for r in rows)
    summary = "".join(
        f'<div class="card"><div class="num">{counts.get(s, 0)}</div><div class="lbl">{esc(s)}</div></div>'
        for s in ORDER
    )
    out = [
        f'<p class="muted">As of {esc(d["as_of"])}. One row per requirement in the owner brief ({len(rows)} rows, '
        f'duplicates merged). Status is judged from what the repository contains today. '
        f'Each row names the gate that blocks it and the number that would clear it. The Evidence column links to '
        f'dashboard pages or repository files; these rows state requirements, not NFL facts. NFL facts sit on the linked pages, '
        f'with official links on each data row.</p>',
        f'<div class="cards">{summary}</div>',
        '<div class="tablewrap"><table class="data"><thead><tr>'
        '<th>ID</th><th>Requirement</th><th>Status</th><th>Blocking gate</th>'
        '<th>Number or condition that clears it</th><th>Evidence</th></tr></thead><tbody>',
    ]
    current = None
    for r in rows:
        if r["area"] != current:
            current = r["area"]
            out.append(f'<tr class="group"><td colspan="6"><strong>{esc(current)}</strong></td></tr>')
        badge = BADGE.get(r["status"], "pending")
        out.append(
            "<tr>"
            f'<td>{esc(r["id"])}</td>'
            f'<td>{esc(r["requirement"])}</td>'
            f'<td><span class="badge {badge}">{esc(r["status"])}</span></td>'
            f'<td>{esc(r["gate"])}</td>'
            f'<td>{esc(r["clears"])}</td>'
            f'<td class="src">{link(r["href"], r["evidence"])}</td>'
            "</tr>"
        )
    out.append("</tbody></table></div>")
    legend = " · ".join(f"<strong>{esc(k)}</strong>: {esc(v)}" for k, v in d["status_legend"].items())
    out.append(f'<p class="muted">Status key — {legend}.</p>')
    return "\n".join(out)


def audit_block():
    with open(os.path.join(DASH, "data/repo-audit.json"), encoding="utf-8") as fh:
        a = json.load(fh)
    p = a["pages"]
    j = a["json"]
    size_mb = a["size"]["total_tracked_bytes"] / 1_000_000
    out = [
        f'<p class="muted">Generated by <code>{esc(a["generated_by"])}</code> on branch <code>{esc(a["branch"])}</code> '
        f'at commit <code>{esc(a["head_commit"][:12])}</code>. Each line below is the output of a check that can be re-run.</p>',
        '<table class="data"><thead><tr><th>Check</th><th>Result</th><th>Status</th></tr></thead><tbody>',
        f'<tr><td>Tracked JSON files that parse</td><td>{j["json_files_checked"] - len(j["parse_failures"])} of {j["json_files_checked"]}</td>'
        f'<td><span class="badge {"verified" if not j["parse_failures"] else "flagged"}">{"Pass" if not j["parse_failures"] else "Fail"}</span></td></tr>',
        f'<tr><td>Internal links in fl2-dashboard pages that resolve</td><td>{p["pages_checked"]} pages, {len(p["broken_internal_links"])} broken</td>'
        f'<td><span class="badge {"verified" if not p["broken_internal_links"] else "flagged"}">{"Pass" if not p["broken_internal_links"] else "Fail"}</span></td></tr>',
        f'<tr><td>In-page anchors that resolve</td><td>{len(p["missing_anchors"])} missing (3 found and fixed on 2026-11-16, Flagged F-A1)</td>'
        f'<td><span class="badge {"verified" if not p["missing_anchors"] else "flagged"}">{"Pass" if not p["missing_anchors"] else "Fail"}</span></td></tr>',
    ]
    if p["table_rows_without_source_link"]:
        for r in p["table_rows_without_source_link"]:
            out.append(
                f'<tr><td>Table rows with a Source column but no link ({esc(r["page"])})</td>'
                f'<td>{r["rows_without_source_link"]} of {r["rows_with_source_column"]} rows</td>'
                '<td><span class="badge pending">Open — Flagged F-S1</span></td></tr>')
    for r in p.get("table_rows_linking_only_to_site_pages", []):
        out.append(
            f'<tr><td>Table rows whose only link is to a dashboard or repository page ({esc(r["page"])})</td>'
            f'<td>{r["rows_linking_only_to_site_pages"]} of {r["rows_with_source_column"]} rows</td>'
            '<td><span class="badge design">Info — requirement or internal-evidence rows</span></td></tr>')
    out.append(
        f'<tr><td>Tracked repository size</td><td>{size_mb:.1f} MB, of which signal/ is '
        f'{a["size"]["tracked_bytes_by_top_directory"].get("signal", 0) / 1_000_000:.1f} MB</td>'
        '<td><span class="badge pending">Noted — Flagged F-S2</span></td></tr>')
    out.append("</tbody></table>")

    out.append('<h3>Week 10 injury row totals stored in each file</h3>'
               '<p class="muted">The same report is stored with four different totals. Counts only; no player names.</p>'
               '<table class="data"><thead><tr><th>File</th><th class="num">Rows</th><th class="num">Clubs</th><th>Note</th><th>Source</th></tr></thead><tbody>')
    for r in a["injury_row_counts"]:
        clubs = "" if r.get("teams") is None else esc(r["teams"])
        out.append(
            f'<tr><td><code>{esc(r["file"])}</code></td><td class="num">{esc(r["rows"])}</td>'
            f'<td class="num">{clubs}</td><td>{esc(r["note"])}</td>'
            '<td class="src"><a href="https://www.nfl.com/injuries/" target="_blank" rel="noopener">nfl.com/injuries</a></td></tr>')
    out.append("</tbody></table>")
    out.append(
        '<p class="muted">Coordination board: ' + esc(a["coordination"]["lines"]) + ' lines in COORDINATION.md. '
        'Pages configuration checked on 2026-11-16 with <code>gh api repos/sassnarep3-star/FL2/pages</code> '
        '(source <code>main /</code>, legacy build).</p>')
    return "\n".join(out)


def main():
    replace_block(os.path.join(DASH, "index.html"), "readiness", readiness_block())
    replace_block(os.path.join(DASH, "repo-review.html"), "audit", audit_block())
    print("rendered readiness and audit blocks")
    return 0


if __name__ == "__main__":
    sys.exit(main())
